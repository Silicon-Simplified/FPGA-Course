#!/usr/bin/env python3
"""Episode 28: generate an 8-tap low-pass FIR (Hamming-windowed sinc, cutoff 0.2 x fs, 16-bit coefficients) as a transposed-form Verilog module.   python3 scripts/gen_fir.py"""
import os
import numpy as np
HERE = os.path.dirname(os.path.abspath(__file__))
N, FC = 8, 0.2
n = np.arange(N) - (N - 1) / 2
h = np.sinc(2 * FC * n) * np.hamming(N)
h = h / h.sum()                                   # unity DC gain
hq = np.round(h * 2 ** 15).astype(int)            # Q1.15
np.savetxt(os.path.join(HERE, "..", "reports", "fir_coeffs.txt"), hq, fmt="%d")
L = ["// Episode 28 - 8-tap transposed-form FIR, 16-bit signed samples and Q1.15 coefficients (generated by scripts/gen_fir.py).",
     "// x -> xr (A register) -> m_k = h_k * xr (M register) -> p_k = m_k + p_(k+1) (P register); y = p_0.  Three register stages (A, M, P).",
     "module fir8 (input wire clk, input wire signed [15:0] x, output wire signed [34:0] y);",
     "    reg signed [15:0] xr = 0;", "    always @(posedge clk) xr <= x;"]
for k in range(N):
    L.append(f"    wire signed [15:0] h{k} = {int(hq[k])};")
for k in range(N):
    L.append(f"    reg signed [31:0] m{k} = 0; always @(posedge clk) m{k} <= h{k} * xr;")
for k in range(N - 1, -1, -1):
    nxt = f" + p{k + 1}" if k < N - 1 else ""
    L.append(f"    reg signed [34:0] p{k} = 0; always @(posedge clk) p{k} <= m{k}{nxt};")
L += ["    assign y = p0;", "endmodule", ""]
open(os.path.join(HERE, "..", "rtl", "fir8.v"), "w").write("\n".join(L))
print("coeffs", hq.tolist(), "sum", int(hq.sum()))
