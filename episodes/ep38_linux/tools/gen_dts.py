#!/usr/bin/env python3
"""Episode 38 - generate device-tree fragments (UIO nodes) for the peripherals of episodes 35 and 37 from their Vivado address maps.
   usage: python3 tools/gen_dts.py [ep35_address_map.txt ep37_address_map.txt]
   The output was NOT compiled with dtc (not installed here): the checks at the end only test the text (braces, semicolons, values)."""
import re
import sys
import os

HERE = os.path.dirname(os.path.abspath(__file__))
def find_episodes(start):                              # the folder that contains ep35_axil: works in the course folder (.../ep38/code/tools) and in the GitHub repo (.../ep38/tools)
    d = start
    for _ in range(6):
        d = os.path.dirname(d)
        if os.path.isdir(os.path.join(d, "ep35_axil")):
            return d
    sys.exit("cannot find the ep35_axil folder: pass the two address_map.txt files as arguments")


EPS = find_episodes(HERE) if len(sys.argv) < 3 else ""
args = sys.argv[1:]
def amap(ep):                                          # the course folder keeps the reports under <episode>/code/reports, the GitHub repo under <episode>/reports
    for sub in (("code", "reports"), ("reports",)):
        p = os.path.join(EPS, ep, *sub, "address_map.txt")
        if os.path.exists(p):
            return p
    sys.exit(f"no address_map.txt found for {ep}")


m35 = args[0] if len(args) > 0 else amap("ep35_axil")
m37 = args[1] if len(args) > 1 else amap("ep37_irq")


def seg(path):
    t = open(path).read()
    m = re.search(r"SEG_(\w+?)_reg0 offset=0x([0-9A-Fa-f]+) range=0x([0-9A-Fa-f]+)", t)
    return m.group(1), int(m.group(2), 16), int(m.group(3), 16)


def node(label, name, base, size, irq_spi=None):
    s = [f"/* generated by tools/gen_dts.py from the Vivado address map: do not edit */", "&amba_pl {", f"\t{label}: {name}@{base:x} {{", '\t\tcompatible = "generic-uio";', f"\t\treg = <0x{base:x} 0x{size:x}>;"]
    if irq_spi is not None:
        s += ["\t\tinterrupt-parent = <&intc>;", f"\t\tinterrupts = <0 {irq_spi} 4>;   /* SPI {irq_spi} = GIC ID {32 + irq_spi}, level high */"]
    s += ["\t};", "};", ""]
    return "\n".join(s)


out = {}
n, b, z = seg(m35); out["pwm_uio.dtsi"] = node("pwm0", "pwm", b, z); r35 = (n, b, z)
n, b, z = seg(m37); out["btn_irq_uio.dtsi"] = node("btn_irq0", "btn-irq", b, z, irq_spi=29); r37 = (n, b, z)
os.makedirs(os.path.join(HERE, "..", "dts"), exist_ok=True)
lines = []
for fn, text in out.items():
    open(os.path.join(HERE, "..", "dts", fn), "w").write(text)
    ok_braces = text.count("{") == text.count("}")
    ok_semi = all(l.rstrip().endswith((";", "{", "*/")) for l in text.splitlines() if l.strip())
    m = re.search(r"reg = <0x([0-9a-f]+) 0x([0-9a-f]+)>", text)
    unit = re.search(r"@([0-9a-f]+) \{", text).group(1)
    ok_unit = unit == m.group(1)
    assert ok_braces and ok_semi and ok_unit, fn
    lines.append(f"{fn}: braces balanced {ok_braces}, every line ends in ; or {{ {ok_semi}, unit address @{unit} equals reg base {ok_unit}, reg = base 0x{m.group(1)} size 0x{m.group(2)}")
assert 32 + 29 == 61                                  # SPI 29 is the GIC ID 61 used in episode 37
assert r35[1] == 0x40000000 and r35[2] == 0x1000 and r37[1] == 0x40000000 and r37[2] == 0x1000
lines.append("SPI 29 + 32 = GIC ID 61 (episode 37): True")
open(os.path.join(HERE, "..", "reports", "dts_check.txt"), "w").write("\n".join(lines) + "\n")
print("\n".join(lines))
